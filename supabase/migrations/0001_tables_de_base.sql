-- V and B — Tables de base (héritées de l'ancienne app, état au 14/10/2026)
-- Réexécutable. Reprend la création des 9 tables d'origine (ancien script
-- « Setup COMPLET », jamais versionné jusqu'ici), sans les règles d'accès :
-- elles sont posées par 0004 (équipe seulement) puis 0005 (périmètre des
-- Coachs et des RR, référentiels écrits par le Directeur de réseau).
-- Les tables sont fermées (RLS sans règle) jusqu'au passage de 0004.
--
-- Noms internes conservés de l'ancienne app : cs = Coach, dr = Responsable
-- Régional, store = magasin (identifié par son nom).
-- ════════════════════════════════════════════════════════════════

-- ── Affectations : Coach de chaque magasin, datées (effet le 1er du mois)
CREATE TABLE IF NOT EXISTS public.reassigns (
  id         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  store      text NOT NULL,
  cs         text,                   -- nom du Coach
  date       date NOT NULL,
  note       text,
  type       text DEFAULT 'manual',  -- 'manual' | 'pre' | 'initial'
  created_at timestamptz DEFAULT now()
);

-- ── Recrues (Coachs ou Techniciens à venir, ou fictifs pour simuler)
CREATE TABLE IF NOT EXISTS public.recruits (
  id         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  name       text NOT NULL,
  start      date,                   -- entrée (début de formation)
  post       date,                   -- prise de poste
  ville      text,
  color      text DEFAULT '#4caf50',
  lon        double precision,
  lat        double precision,
  fictif     boolean DEFAULT false,
  tech       boolean DEFAULT false,  -- true = Technicien, exclu des calculs de charge
  birth      date,
  created_at timestamptz DEFAULT now()
);
ALTER TABLE public.recruits ADD COLUMN IF NOT EXISTS fictif boolean DEFAULT false;
ALTER TABLE public.recruits ADD COLUMN IF NOT EXISTS tech   boolean DEFAULT false;
ALTER TABLE public.recruits ADD COLUMN IF NOT EXISTS birth  date;

-- ── Coachs : coordonnées, ville, couleur
CREATE TABLE IF NOT EXISTS public.cs_overrides (
  cs_name    text PRIMARY KEY,       -- nom du Coach
  tel        text,
  email      text,
  ville      text,
  color      text,
  lon        double precision,
  lat        double precision,
  fictif     boolean DEFAULT false,
  tech       boolean DEFAULT false,
  birth      date,
  updated_at timestamptz DEFAULT now()
);
ALTER TABLE public.cs_overrides ADD COLUMN IF NOT EXISTS fictif boolean DEFAULT false;
ALTER TABLE public.cs_overrides ADD COLUMN IF NOT EXISTS tech   boolean DEFAULT false;
ALTER TABLE public.cs_overrides ADD COLUMN IF NOT EXISTS birth  date;
-- Numéro interne présent dans la base en ligne (ancienne app), non utilisé par l'app
ALTER TABLE public.cs_overrides ADD COLUMN IF NOT EXISTS id bigint GENERATED BY DEFAULT AS IDENTITY;

-- ── Fiche de chaque magasin (complète la liste rangée dans app_config, clé store_adds)
CREATE TABLE IF NOT EXISTS public.store_overrides (
  store_name text PRIMARY KEY,
  tel        text,
  email_mag  text,
  tel_cs     text,
  email_cs   text,
  resp       text,
  tel_resp   text,
  email_resp text,
  adj        text,
  tel_adj    text,
  addr       text,
  num        text,
  rue        text,
  cp         text,
  ville      text,
  code       text,
  plat       text,
  open_date  date,
  dept       text,
  franchise  boolean DEFAULT true,   -- true = franchisé, false = intégré
  pays       text,                   -- vide = France
  rr         text,                   -- identifiant du RR qui gère le magasin en direct
  lon        double precision,
  lat        double precision,
  updated_at timestamptz DEFAULT now()
);
ALTER TABLE public.store_overrides ADD COLUMN IF NOT EXISTS email_mag text;
ALTER TABLE public.store_overrides ADD COLUMN IF NOT EXISTS num       text;
ALTER TABLE public.store_overrides ADD COLUMN IF NOT EXISTS rue       text;
ALTER TABLE public.store_overrides ADD COLUMN IF NOT EXISTS cp        text;
ALTER TABLE public.store_overrides ADD COLUMN IF NOT EXISTS ville     text;
ALTER TABLE public.store_overrides ADD COLUMN IF NOT EXISTS franchise boolean DEFAULT true;
ALTER TABLE public.store_overrides ADD COLUMN IF NOT EXISTS rr        text;
ALTER TABLE public.store_overrides ADD COLUMN IF NOT EXISTS pays      text;
-- Numéro interne présent dans la base en ligne (ancienne app), non utilisé par l'app
ALTER TABLE public.store_overrides ADD COLUMN IF NOT EXISTS id bigint GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE public.store_overrides ALTER COLUMN dept TYPE text USING dept::text;

-- ── Réglages et référentiels en clé / valeur (value = texte JSON, détail dans docs/base-de-donnees.md)
CREATE TABLE IF NOT EXISTS public.app_config (
  id         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  key        text UNIQUE NOT NULL,
  value      text,
  updated_at timestamptz DEFAULT now()
);

-- ── Agenda de l'équipe
CREATE TABLE IF NOT EXISTS public.events (
  id         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  title      text NOT NULL,
  type       text DEFAULT 'event',
  start_date date NOT NULL,
  end_date   date,                   -- vide = un seul jour
  notes      text,
  color      text DEFAULT '#7c3aed',
  created_at timestamptz DEFAULT now()
);

-- ── Congés d'un Coach ou d'un RR
CREATE TABLE IF NOT EXISTS public.leaves (
  id         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  person     text NOT NULL,
  role       text DEFAULT 'cs',      -- 'cs' (Coach) | 'dr' (RR)
  start_date date NOT NULL,
  end_date   date NOT NULL,
  notes      text,
  created_at timestamptz DEFAULT now()
);

-- ── Chiffres mensuels par magasin
CREATE TABLE IF NOT EXISTS public.store_finance (
  store_name text NOT NULL,
  month      date NOT NULL,
  ca_cave    numeric,
  ca_bar     numeric,
  ebitda     numeric,
  panier     numeric,
  freq       numeric,
  updated_at timestamptz DEFAULT now(),
  PRIMARY KEY (store_name, month)
);
ALTER TABLE public.store_finance ADD COLUMN IF NOT EXISTS ca_ext    numeric; -- CA marché extérieur
ALTER TABLE public.store_finance ADD COLUMN IF NOT EXISTS pm_cave   numeric; -- panier moyen HT cave
ALTER TABLE public.store_finance ADD COLUMN IF NOT EXISTS flux_cave numeric;
ALTER TABLE public.store_finance ADD COLUMN IF NOT EXISTS pm_bar    numeric; -- panier moyen HT bar
ALTER TABLE public.store_finance ADD COLUMN IF NOT EXISTS flux_bar  numeric;
ALTER TABLE public.store_finance ADD COLUMN IF NOT EXISTS marge     numeric; -- en %

-- ── Visites, appels et audits (une ligne par magasin ; group_id relie une tournée)
CREATE TABLE IF NOT EXISTS public.visits (
  id              bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  group_id        text,
  store           text NOT NULL,
  visit_date      date NOT NULL,
  type            text DEFAULT 'terrain',
  visitor         text,                       -- participants séparés par « , »
  signed_required boolean DEFAULT false,
  signed_url      text,
  signed_date     date,
  docs            jsonb DEFAULT '[]'::jsonb,
  notes           text,
  created_at      timestamptz DEFAULT now()
);
ALTER TABLE public.visits ADD COLUMN IF NOT EXISTS group_id        text;
ALTER TABLE public.visits ADD COLUMN IF NOT EXISTS visitor         text;
ALTER TABLE public.visits ADD COLUMN IF NOT EXISTS signed_required boolean DEFAULT false;
ALTER TABLE public.visits ADD COLUMN IF NOT EXISTS signed_url      text;
ALTER TABLE public.visits ADD COLUMN IF NOT EXISTS signed_date     date;
ALTER TABLE public.visits ADD COLUMN IF NOT EXISTS docs            jsonb DEFAULT '[]'::jsonb;
ALTER TABLE public.visits ADD COLUMN IF NOT EXISTS notes           text;
CREATE INDEX IF NOT EXISTS visits_store_idx ON public.visits (store);
CREATE INDEX IF NOT EXISTS visits_date_idx  ON public.visits (visit_date);

-- ── Tables fermées tant que les règles d'accès (0004, 0005) ne sont pas posées
ALTER TABLE public.reassigns       ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.recruits        ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.cs_overrides    ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.store_overrides ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.app_config      ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.events          ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.leaves          ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.store_finance   ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.visits          ENABLE ROW LEVEL SECURITY;
